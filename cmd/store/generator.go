package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"github.com/iancoleman/strcase"
)

func write(path string, packageName string, lexem *Lexem) {
	packageTemplate := template.Must(template.New("").Funcs(template.FuncMap{
		"title": func(value string) string {
			return strings.ToUpper(value[:1]) + value[1:]
		},
		"contains": func(slice []string, s string) bool {
			for _, item := range slice {
				if item == s {
					return true
				}
			}
			return false
		},
		"lowerCamel": strcase.ToLowerCamel,
	}).Parse(`// Code generated by sql.store; DO NOT EDIT.
package {{ .PackageName }}

{{ if and (gt (len .Lexem.Imports) 0) (or (not .Lexem.NoNew) (not .Lexem.NoUnwrap)) -}}
import (
	{{- range .Lexem.Imports }}
	{{ . }}
	{{- end }}
)
{{- end }}

var {{ .Lexem.Name }}Mappings = map[string]string{
	{{- range .Lexem.Fields }}
		"{{ lowerCamel .Source }}": "{{ .Field }}",
	{{- end }}
}

{{ if not .Lexem.NoNew -}}
func new{{ title .Lexem.Name}}(m {{ .Lexem.Pointer }}{{ if ne .Lexem.Module "" }}{{ .Lexem.Module }}.{{ end }}{{ .Lexem.Model }}) *{{ .Lexem.Name }} {
	return &{{ .Lexem.Name }}{
		{{- range .Lexem.Fields }}
		{{ .Name }}: 
			{{- if .Wrapped -}}
			{{ $.SqlWrapper }}.NewJson(m.{{ .Source }}),
			{{- else if eq .Convert "csv" -}}
			func (v []string) *string { if len(v) == 0 { return nil } else { s := strings.Join(v, ","); return &s }}(m.{{ .Source }}),
			{{- else -}}
			m.{{ .Source }},
			{{- end }}
		{{- end }}
	}
}
{{- end }}

{{ if not .Lexem.NoUnwrap -}}
func (m *{{ .Lexem.Name }}) Unwrap() {{ .Lexem.Pointer }}{{ if ne .Lexem.Module "" }}{{ .Lexem.Module }}.{{ end }}{{ .Lexem.Model }} {
	return {{ if eq .Lexem.Pointer "*" }}&{{ end }}{{ if ne .Lexem.Module "" }}{{ .Lexem.Module }}.{{ end }}{{ .Lexem.Model }}{
		{{- range .Lexem.Fields }}
		{{ .Source }}: 
			{{- if .Wrapped -}}
			m.{{ .Name }}.Unwrap(),
			{{- else if eq .Convert "csv" -}}
			func (v *string) []string { if v == nil { return nil } else { return strings.Split(*v, ",") }}(m.{{ .Name }}),
			{{- else -}}
			m.{{ .Name }},
			{{- end -}}
		{{- end }}
	}
}
{{- end }}

func (m *{{ .Lexem.Name }}) Mappings() map[string]string {
	return {{ .Lexem.Name }}Mappings
}

func (m *{{ .Lexem.Name }}) Updates() map[string]any {
	return map[string]any{
		{{- range .Lexem.Fields }}
		{{- if not .Readonly }}
		"{{ .Field }}": m.{{ .Name }},
		{{- end }}
		{{- end }}
	}
}

{{ range $group := .Lexem.UpdateGroups }}
func (m *{{ $.Lexem.Name }}) Updates{{ title $group }}() map[string]any {
	return map[string]any{
		{{- range $.Lexem.Fields }}
		{{- if contains .UpdateGroups $group }}
		"{{ .Field }}": m.{{ .Name }},
		{{- end }}
		{{- end }}
	}
}
{{ end }}

func (m *{{ .Lexem.Name }}) Inserts() ([]string, []any) {
	return []string{
		{{- range .Lexem.Fields }}
		{{- if not .Readonly }}
		"{{ .Field }}",
		{{- end }}
		{{- end }}
	}, []any{
		{{- range .Lexem.Fields }}
		{{- if not .Readonly }}
		m.{{ .Name }},
		{{- end }}
		{{- end }}
	}
}

{{ range $group := .Lexem.InsertGroups }}
func (m *{{ $.Lexem.Name }}) Inserts{{ title $group }}() ([]string, []any) {
	return []string{
		{{- range $.Lexem.Fields }}
		{{- if contains .InsertGroups $group }}
		"{{ .Field }}",
		{{- end }}
		{{- end }}
	}, []any{
		{{- range $.Lexem.Fields }}
		{{- if contains .InsertGroups $group }}
		m.{{ .Name }},
		{{- end }}
		{{- end }}
	}
}
{{ end }}

func (m *{{ .Lexem.Name }}) Returns() []string {
	return []string{
		{{- range .Lexem.Fields }}
		"{{ .Field }}",
		{{- end }}
	}
}

func (m *{{ .Lexem.Name }}) Scan() []any {
	return []any{
		{{- range .Lexem.Fields }}
		&m.{{ .Name }},
		{{- end }}
	}
}
`))

	var buf bytes.Buffer
	err := packageTemplate.Execute(&buf, map[string]any{
		"PackageName": packageName,
		"Lexem":       lexem,
		"SqlWrapper":  sqlWrapper,
	})
	if err != nil {
		panic(err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		panic(fmt.Errorf("error formatting generated code: %v\nOriginal source:\n%s", err, buf.String()))
	}

	fileName := toSnake(lexem.Name)
	out, err := os.Create(filepath.Join(path, fmt.Sprintf("%s_gen.go", fileName)))
	if err != nil {
		panic(err)
	}
	defer out.Close()

	if _, err := out.Write(formatted); err != nil {
		panic(err)
	}
}

func toSnake(source string) string {
	var builder strings.Builder
	for i, c := range source {
		if c >= 'A' && c <= 'Z' {
			if i > 0 {
				builder.WriteByte(byte('_'))
			}
			c += 32
		}
		builder.WriteByte(byte(c))
	}
	return builder.String()
}
