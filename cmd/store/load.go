package main

import (
	"bufio"
	"fmt"
	"go/token"
	"go/types"
	"os"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const (
	buildTag        = "store"
	generatedHeader = "// Code generated by sql.store; DO NOT EDIT."
)

// Under its own tag the package is missing everything this generator writes, so
// type errors are the normal state of a healthy input: pkg.Errors cannot be a
// blanket failure here.
func loadPackage(dir string) (*packages.Package, error) {
	cfg := &packages.Config{
		// NeedSyntax: a stored struct is unexported, and export data omits it.
		Mode: packages.NeedName | packages.NeedSyntax | packages.NeedTypes |
			packages.NeedDeps | packages.NeedImports,
		Dir:        dir,
		Fset:       token.NewFileSet(),
		BuildFlags: []string{"-tags", buildTag},
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return nil, fmt.Errorf("loading %s: %w", dir, err)
	}
	if len(pkgs) == 0 {
		return nil, fmt.Errorf("no package in %s", dir)
	}
	pkg := pkgs[0]
	if err := blockingError(pkg); err != nil {
		return nil, err
	}
	if pkg.Types == nil {
		return nil, fmt.Errorf("no type information for %s", pkg.PkgPath)
	}
	return pkg, nil
}

func blockingError(pkg *packages.Package) error {
	for _, e := range pkg.Errors {
		switch e.Kind {
		case packages.ListError:
			return fmt.Errorf("%s: %s", pkg.PkgPath, e.Msg)
		case packages.ParseError:
			if ownsOutput(errorFile(e.Pos)) {
				continue
			}
			return fmt.Errorf("%s", e)
		}
	}
	return nil
}

// "file:line:col", and a Windows path carries a colon of its own.
func errorFile(pos string) string {
	for range 2 {
		i := strings.LastIndexByte(pos, ':')
		if i < 0 {
			return pos
		}
		pos = pos[:i]
	}
	return pos
}

// Read line by line, not parsed: the header is the only marker that survives
// output too broken to parse — which is the output this has to recognise.
func ownsOutput(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer func() { _ = f.Close() }()

	scanner := bufio.NewScanner(f)
	for i := 0; scanner.Scan() && i < 8; i++ {
		line := strings.TrimSpace(scanner.Text())
		if line == generatedHeader {
			return true
		}
		if strings.HasPrefix(line, "package ") {
			return false
		}
	}
	return false
}

type storedType struct {
	name  string
	named *types.Named
	st    *types.Struct
	pos   token.Pos
}

// Sorted: a package scope iterates a map, and the output is compared to a golden.
func storedTypesIn(pkg *packages.Package, file string) []storedType {
	var found []storedType
	scope := pkg.Types.Scope()
	for _, name := range scope.Names() {
		tn, ok := scope.Lookup(name).(*types.TypeName)
		if !ok {
			continue
		}
		named, ok := tn.Type().(*types.Named)
		if !ok {
			continue
		}
		st, ok := named.Underlying().(*types.Struct)
		if !ok {
			continue
		}
		pos := named.Obj().Pos()
		if !samePath(pkg.Fset.Position(pos).Filename, file) {
			continue
		}
		found = append(found, storedType{name: name, named: named, st: st, pos: pos})
	}
	sort.Slice(found, func(i, j int) bool { return found[i].pos < found[j].pos })
	return found
}
